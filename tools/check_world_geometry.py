#!/usr/bin/env python3
"""Independent E03 source-to-mesh audit, including destructive in-memory fixtures.

Reads prepared triangles directly; does not compare against regenerated byte output.
Default report stays in ignored data/cache; existing data/reports files are protected.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
import math
from collections import Counter
from pathlib import Path

from shapely.geometry import LineString, Point, Polygon, MultiPolygon, box, shape
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[1]
AREA_TOL = .02
DIST_TOL = .00001
Y_TOL = .000002


class AuditError(ValueError):
    pass


def require(condition, code, detail):
    if not condition:
        raise AuditError(f"{code}: {detail}")


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def cross(a, b):
    return [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]]


def dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def mesh_audit(mesh, expected, bottom, top):
    """Recover projected cap and wall geometry from actual vertex triples."""
    label = mesh['id']
    vertices, normals = mesh['vertices'], mesh['normals']
    require(len(vertices) == len(normals) and len(vertices) > 0 and len(vertices) % 9 == 0,
            'array_shape', label)
    require(all(isinstance(v, (float, int)) and math.isfinite(v) for v in vertices+normals), 'finite', label)
    require(abs(mesh['bottom_y_m']-bottom) <= Y_TOL and
            ((top is None and mesh['top_y_m'] is None) or
             (top is not None and mesh['top_y_m'] is not None and abs(mesh['top_y_m']-top) <= Y_TOL)),
            'height', label)
    cap_y = bottom if top is None else top
    caps, bottoms, side_lines = [], [], []
    for offset in range(0, len(vertices), 9):
        p = [vertices[offset+i:offset+i+3] for i in (0, 3, 6)]
        ns = [normals[offset+i:offset+i+3] for i in (0, 3, 6)]
        edge1 = [p[1][i]-p[0][i] for i in range(3)]
        edge2 = [p[2][i]-p[0][i] for i in range(3)]
        front = [-v for v in cross(edge1, edge2)]
        length = math.sqrt(dot(front, front))
        require(length > 1e-12, 'degenerate_triangle', label)
        front = [v/length for v in front]
        require(all(abs(dot(n, n)-1) < 2e-6 and dot(front, n) > 1-2e-6 for n in ns),
                'clockwise_normal', f'{label} triangle {offset//9}')
        require(all(bottom-Y_TOL <= q[1] <= cap_y+Y_TOL for q in p), 'height', label)
        projected = Polygon([(q[0], q[2]) for q in p])
        if all(abs(q[1]-cap_y) <= Y_TOL for q in p):
            require(front[1] > 1-2e-6, 'top_normal', label)
            caps.append(projected)
        elif top is not None and all(abs(q[1]-bottom) <= Y_TOL for q in p):
            require(front[1] < -1+2e-6, 'bottom_normal', label)
            bottoms.append(projected)
        else:
            require(top is not None and abs(front[1]) < 2e-6, 'side_normal', label)
            require(all(min(abs(q[1]-bottom), abs(q[1]-top)) <= Y_TOL for q in p), 'side_height', label)
            xz = list(dict.fromkeys((q[0], q[2]) for q in p))
            require(len(xz) == 2, 'side_projection', label)
            line = LineString(xz)
            require(line.difference(expected.boundary.buffer(DIST_TOL)).length <= DIST_TOL,
                    'side_boundary', label)
            midpoint = line.interpolate(.5, normalized=True)
            # A front normal must point into the complement, including inner rings.
            distance = min(.0001, line.length*.01)
            outward = Point(midpoint.x+front[0]*distance, midpoint.y+front[2]*distance)
            inward = Point(midpoint.x-front[0]*distance, midpoint.y-front[2]*distance)
            require(not expected.contains(outward) and expected.contains(inward), 'side_outward', label)
            side_lines.append(line)
    def coverage(triangles, kind):
        require(bool(triangles), kind+'_coverage', label+' missing cap')
        union = unary_union(triangles)
        error = union.symmetric_difference(expected).area
        hausdorff = union.hausdorff_distance(expected)
        overlap = abs(sum(t.area for t in triangles)-union.area)
        require(error <= AREA_TOL and hausdorff <= DIST_TOL and overlap <= AREA_TOL,
                kind+'_coverage', f'{label} error={error}, hausdorff={hausdorff}, overlap={overlap}')
        # Explicitly retain disconnected parts and holes, rather than trust metadata.
        polygons = [union] if union.geom_type == 'Polygon' else list(union.geoms)
        sources = [expected] if expected.geom_type == 'Polygon' else list(expected.geoms)
        require(len(polygons) == len(sources) and sum(len(p.interiors) for p in polygons) ==
                sum(len(p.interiors) for p in sources), kind+'_topology', label)
        return {'symmetric_difference_m2':error, 'hausdorff_m':hausdorff, 'overlap_m2':overlap}
    result = coverage(caps, 'top')
    if top is not None:
        coverage(bottoms, 'bottom')
        require(bool(side_lines) and unary_union(side_lines).hausdorff_distance(expected.boundary) <= DIST_TOL,
                'side_coverage', label)
    return result


def load_inputs(root):
    names = ['features', 'heights', 'terrain', 'walkable_areas', 'driveable_areas', 'coordinate_reference']
    docs = {name:json.loads((root/f'data/processed/{name}.json').read_text()) for name in names}
    docs['display'] = json.loads((root/'config/world_display.json').read_text())
    docs['region'] = json.loads((root/'config/region.json').read_text())
    return docs


def expected_meshes(docs):
    features = docs['features']['features']
    heights = {r['feature_id']:r for r in docs['heights']['records']}
    terrain = {r['feature_id']:r for r in docs['terrain']['records']}
    display = docs['display']
    plane = docs['terrain']['temporary_support_plane']
    expected = {'temporary_support':(box(*plane['local_xz_extent']), plane['ground_y_m'], None, None, 'Ground')}
    for feature in features:
        fid = feature['feature_id']; h = heights[fid]; ground = terrain[fid]['ground_y_m']
        geometry = shape(feature['geometry'])
        if h['emit_coarse_body']:
            require(feature['source_kind'] == 'building' and ground is not None, 'body_ground_selection', fid)
            expected[fid] = (geometry, ground+h['min_height_m'], ground+h['height_m'], feature, 'Buildings')
        elif ground is not None and feature['source_kind'] == 'land_area':
            tags = feature['source_tags']
            material = 'sand' if tags.get('natural') == 'sand' or tags.get('surface') == 'sand' else 'water' if tags.get('natural') == 'water' else 'grass' if tags.get('leisure') in ['park','garden'] or tags.get('landuse') in ['grass','forest','recreation_ground'] else 'land'
            expected[fid] = (geometry, ground+display['surface_offsets_m']['land']+display['land_material_offsets_m'][material], None, feature, 'Ground')
        elif ground is not None and feature['generation']['role'] in ['boundary_line_candidate', 'boundary_area_candidate']:
            wall = geometry.buffer(display['barrier_thickness_m']/2, cap_style='flat', join_style='mitre') if geometry.geom_type in ['LineString','MultiLineString'] else geometry
            expected[fid] = (wall, ground+h['min_height_m'], ground+h['height_m'], feature, 'Barriers')
    candidates = {}
    for mode, name in [('walk','walkable_areas'), ('drive','driveable_areas')]:
        for record in docs[name]['records']:
            require(record['runtime_permission'] is None and record['runtime_surface_ready'] is False, 'source_permission', record['feature_id'])
            if record['candidate_surface_geometry'] is not None:
                require(record['ground_y_m'] is not None, 'surface_ground', record['feature_id'])
                candidates.setdefault(record['feature_id'], {})[mode] = record
    lookup = {f['feature_id']:f for f in features}
    for fid, modes in candidates.items():
        mode = 'drive' if 'drive' in modes else 'walk'; record = modes[mode]
        expected[fid+':display_surface'] = (shape(record['candidate_surface_geometry']),
            record['ground_y_m']+display['surface_offsets_m'][mode], None, lookup[fid], 'Routes')
    return expected, candidates


def audit_world(world, docs):
    expected, candidates = expected_meshes(docs)
    meshes = world['meshes']; ids = [m['id'] for m in meshes]
    require(len(ids) == len(set(ids)), 'duplicate_mesh', 'IDs must be unique')
    require(set(ids) == set(expected), 'source_selection', f'missing={sorted(set(expected)-set(ids))[:5]}, extra={sorted(set(ids)-set(expected))[:5]}')
    require(world['coordinate_system'] == docs['features']['coordinate_system'] and
            docs['region']['meters_per_world_unit'] == 1 and
            world['coordinate_system']['unit'] == 'metre' and
            world['coordinate_system']['world_axes'] == {'x':'east','y':'up','z':'south'}, 'unit_axes', 'coordinate contract')
    require(all(docs[n]['coordinate_system'] == world['coordinate_system'] for n in
                ['heights','terrain','walkable_areas','driveable_areas']) and
            world['coordinate_system']['origin_lon_lat'] == docs['region']['origin_lon_lat'],
            'unit_axes', 'source coordinate contracts')
    require(world['display'] == docs['display'], 'display_contract', 'configuration')
    require(world['scope'] == {'collision':False,'walkability_verified':False,'physical_terrain_verified':False,'playable_boundary':None,'spawn':None}, 'permission', 'world scope')
    source_decisions = world['source_decisions']
    require(len(source_decisions) == len(docs['features']['features']) and
            {r['feature_id'] for r in source_decisions} == {f['feature_id'] for f in docs['features']['features']}, 'decision_coverage', 'all source records')
    ledger = {r['feature_id']:r for r in source_decisions}
    unresolved = [r for r in docs['terrain']['records'] if r['ground_y_m'] is None]
    require(len(unresolved) == 132, 'ground_hold_count', len(unresolved))
    for r in unresolved:
        require(r['feature_id'] not in ids and r['feature_id']+':display_surface' not in ids and
                ledger[r['feature_id']]['display_decision'].startswith('held_ground_unresolved:'), 'ground_hold', r['feature_id'])
    results = []
    heights = {r['feature_id']:r for r in docs['heights']['records']}
    for mesh in meshes:
        geometry, bottom, top, feature, role = expected[mesh['id']]
        require(mesh['role'] == role, 'source_role', mesh['id'])
        meta = mesh['metadata']
        require(meta['runtime_permission'] is None and meta['collision_generated'] is False, 'permission', mesh['id'])
        require(meta['feature_id'] == (feature['feature_id'] if feature else None) and
                meta['source_refs'] == (feature['source_refs'] if feature else []), 'source_link', mesh['id'])
        if role in ['Buildings','Barriers']:
            h = heights[feature['feature_id']]
            require(meta['height_class'] == h['height_class'] and meta['height_assumption_id'] == h['assumption_id'], 'height_provenance', mesh['id'])
            if role == 'Buildings':
                require(meta['source_height_m'] == h['height_m'] and meta['source_min_height_m'] == h['min_height_m'] and
                        meta['component_evidence_ids'] == h['component_evidence_ids'], 'height_provenance', mesh['id'])
        if role == 'Routes':
            modes = candidates[feature['feature_id']]
            mode = 'drive' if 'drive' in modes else 'walk'; r = modes[mode]
            require(meta['candidate_modes'] == sorted(modes) and meta['display_mode'] == mode and
                    meta['width_class'] == r['width_class'] and meta['width_assumption_id'] == r['assumption_id'] and
                    meta['runtime_surface_ready'] is False and meta['display_only_movement_candidate'] is True, 'surface_candidate', mesh['id'])
        results.append(mesh_audit(mesh, geometry, bottom, top))
    counts = dict(Counter(m['role'] for m in meshes))
    require(counts == {'Ground':179,'Buildings':635,'Barriers':49,'Routes':370}, 'role_counts', counts)
    require(world['counts']['roles'] == counts and world['counts']['meshes'] == len(meshes) and
            world['counts']['triangles'] == sum(len(m['vertices'])//9 for m in meshes), 'reported_counts', counts)
    anchors = []
    by_fid = {m['metadata']['feature_id']:m for m in meshes if m['role'] != 'Routes'}
    for point in docs['coordinate_reference']['landmark_points'].values():
        fid = next((f['feature_id'] for f in docs['features']['features'] if
                    f['entity_id'] == 'osm:'+point['source_feature_id'].replace('w/','way:').replace('r/','relation:') and f['source_kind'] == ('land_area' if point['name'] == '서울광장' else 'building')), None)
        require(fid in by_fid, 'anchor_selection', point['name'])
        xyz = point['world_xyz_m']; verts = by_fid[fid]['vertices']
        error = min(math.hypot(verts[i]-xyz[0], verts[i+2]-xyz[2]) for i in range(0,len(verts),3))
        require(error <= DIST_TOL, 'anchor_position', f'{point["name"]}: {error}')
        anchors.append({'name':point['name'],'feature_id':fid,'horizontal_vertex_error_m':error})
    # G01 has seven references; the later selected Jeonggwanheon outline is an
    # eighth source-vertex anchor, explicitly derived from G02, not surveyed.
    jeong = next(f for f in docs['features']['features'] if f['feature_id'] == 'osm:way:381755268:building')
    xy = jeong['geometry']['coordinates'][0][0][0]
    verts = by_fid[jeong['feature_id']]['vertices']
    error = min(math.hypot(verts[i]-xy[0], verts[i+2]-xy[1]) for i in range(0,len(verts),3))
    require(error <= DIST_TOL, 'anchor_position', f'정관헌: {error}')
    anchors.append({'name':'정관헌','feature_id':jeong['feature_id'],
                    'horizontal_vertex_error_m':error,'basis':'G02 first exterior source vertex; not an independent survey'})
    require(len(anchors) == 8, 'anchor_count', len(anchors))
    require(world['known_overlaps']['walk_obstacle_pairs'] == len(docs['walkable_areas']['obstacle_conflicts']) == 77 and
            world['known_overlaps']['drive_obstacle_pairs'] == len(docs['driveable_areas']['obstacle_conflicts']) == 133 and
            world['known_overlaps']['policy'] == 'retained, no automatic clipping/access approval', 'known_overlap_retention', 'source conflict records')
    return {'mesh_count':len(meshes), 'role_counts':counts, 'unresolved_ground_held':len(unresolved),
            'anchors':anchors, 'max_cap_area_error_m2':max(r['symmetric_difference_m2'] for r in results),
            'max_cap_hausdorff_m':max(r['hausdorff_m'] for r in results),
            'known_overlaps_retained':world['known_overlaps'],
            'scope':'Source-relative display geometry only; no physical position, terrain, access or walking validation'}


def fixtures(world, docs):
    # Only fixture construction uses the generator; all acceptance tests above read source geometry.
    spec = importlib.util.spec_from_file_location('fixture_generator', ROOT/'tools/prepare_world.py')
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    geometry = MultiPolygon([Polygon([(0,0),(10,0),(10,10),(0,10)],
        [[(2,2),(2,8),(8,8),(8,2)]]), box(20,0,23,4), box(30,0,32,3)])
    fixture = {'id':'synthetic_donut_two_disjoint', **module.mesh_polygon(geometry,0,4)}
    mesh_audit(fixture, geometry, 0, 4)
    outputs = [{'fixture':'donut_and_two_disjoint_polygons','passed':True}]
    def rejection(name, code, action):
        try:
            action()
        except AuditError as error:
            require(str(error).startswith(code+':'), 'fixture_wrong_rejection', f'{name}: {error}')
            outputs.append({'fixture':name,'rejected':True,'check':code,'error':str(error)[:250]})
        else:
            raise AuditError('fixture_not_rejected: '+name)
    missing = copy.deepcopy(fixture)
    del missing['vertices'][:9]; del missing['normals'][:9]
    rejection('missing_top_face','top_coverage',lambda:mesh_audit(missing,geometry,0,4))
    flipped = copy.deepcopy(fixture)
    flipped['vertices'][3:6], flipped['vertices'][6:9] = flipped['vertices'][6:9], flipped['vertices'][3:6]
    rejection('flipped_triangle','clockwise_normal',lambda:mesh_audit(flipped,geometry,0,4))
    filled_geometry = MultiPolygon([box(0,0,10,10),box(20,0,23,4),box(30,0,32,3)])
    filled = {'id':'filled_hole', **module.mesh_polygon(filled_geometry,0,4)}
    rejection('filled_hole','top_coverage',lambda:mesh_audit(filled,geometry,0,4))
    shifted = copy.deepcopy(fixture)
    shifted['vertices'] = [v+.1 if i%3 == 0 else v for i,v in enumerate(shifted['vertices'])]
    rejection('geometry_drift','side_boundary',lambda:mesh_audit(shifted,geometry,0,4))
    duplicate = dict(world); duplicate['meshes'] = list(world['meshes'])
    part = next(f for f in docs['features']['features'] if f['source_kind']=='building_part')
    fake = copy.deepcopy(next(m for m in world['meshes'] if m['role']=='Buildings'))
    fake['id'] = part['feature_id']; fake['metadata']['feature_id'] = part['feature_id']; duplicate['meshes'].append(fake)
    rejection('part_duplicate','source_selection',lambda:audit_world(duplicate,docs))
    unknown = dict(docs); unknown['terrain'] = copy.deepcopy(docs['terrain'])
    body = next(m for m in world['meshes'] if m['role']=='Buildings')['id']
    next(r for r in unknown['terrain']['records'] if r['feature_id']==body)['ground_y_m'] = None
    rejection('unknown_ground','body_ground_selection',lambda:audit_world(world,unknown))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--world',type=Path,default=ROOT/'game/resources/world_geometry/world.json')
    parser.add_argument('--report',type=Path,default=ROOT/'data/cache/world_geometry_check.json')
    parser.add_argument('--skip-fixtures',action='store_true')
    args = parser.parse_args()
    report = args.report.resolve()
    if report.exists() and (ROOT/'data/reports').resolve() in report.parents:
        parser.error('Refusing to overwrite an existing data/reports evidence file')
    result = {'task':'E03','passed':False,'checker_sha256':sha(__file__), 'world_sha256':sha(args.world),
              'tolerances':{'area_m2':AREA_TOL,'hausdorff_m':DIST_TOL,'height_m':Y_TOL},
              'source_sha256':{str(p.relative_to(ROOT)):sha(p) for p in
                  [ROOT/f'data/processed/{n}.json' for n in ['features','heights','terrain','walkable_areas','driveable_areas','coordinate_reference']]+[ROOT/'config/world_display.json',ROOT/'config/region.json']}}
    try:
        world = json.loads(args.world.read_text()); docs = load_inputs(ROOT)
        required_inputs = {'config/region.json','config/world_display.json','data/reports/coordinate_check.json',
            'data/reports/geometry_check.json','data/reports/height_check.json','data/reports/movement_check.json'} | {
            f'data/processed/{n}.json' for n in ['features','heights','terrain','walkable_areas','driveable_areas']}
        supplied_inputs = [entry['file'] for entry in world['provenance']['inputs']]
        require(required_inputs.issubset(supplied_inputs) and len(supplied_inputs) == len(set(supplied_inputs)),
                'input_hash_coverage', 'required source documents and precondition reports')
        require(world['coordinate_contract_sha256'] == sha(ROOT/'config/region.json'), 'coordinate_hash', 'region')
        for entry in world['provenance']['inputs']:
            require(sha(ROOT/entry['file']) == entry['sha256'], 'input_hash', entry['file'])
        require(world['provenance']['generator_sha256'] == sha(ROOT/'tools/prepare_world.py'), 'generator_hash', 'prepare_world.py')
        result['source_comparison'] = audit_world(world,docs)
        result['fixtures'] = [] if args.skip_fixtures else fixtures(world,docs)
        result['passed'] = True
    except (AuditError, KeyError, TypeError, ValueError) as error:
        result['error'] = str(error)
    report.parent.mkdir(parents=True,exist_ok=True)
    report.write_text(json.dumps(result,ensure_ascii=False,indent=2,allow_nan=False)+'\n')
    print(json.dumps({'passed':result['passed'],'report':str(report),'error':result.get('error')},ensure_ascii=False))
    raise SystemExit(0 if result['passed'] else 1)
    raise SystemExit(0 if result['passed'] else 1)


if __name__ == '__main__':
    main()
